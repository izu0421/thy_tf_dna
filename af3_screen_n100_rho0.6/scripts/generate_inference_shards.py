#!/usr/bin/env python3
"""Split job_list_inference.txt into fixed-size shards, each its own sbatch
file requesting 1 GPU for 10 hours (~100 jobs/shard fits comfortably at the
observed ~4 min/job inference throughput).

Output:
  job_lists/shard_XXX.txt        - the ~100 job names for that shard
  slurm_shards/infer_shard_XXX.sbatch
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JOB_LIST = ROOT / "job_list_inference.txt"
JOB_LISTS_DIR = ROOT / "job_lists"
SLURM_DIR = ROOT / "slurm_shards"
LOGS_DIR = ROOT / "logs"

SHARD_SIZE = 100
TIME_LIMIT = "10:00:00"

# Plain string.replace() templating (not str.format) - the body is real bash
# full of ${...} which would otherwise have to be escaped as {{...}}.
SBATCH_TEMPLATE = r"""#!/bin/bash
#SBATCH --job-name=af3_infer_@@TAG@@
#SBATCH --output=logs/af3_infer_@@TAG@@_%j.log
#SBATCH --time=@@TIME@@
#SBATCH --cpus-per-task=4
#SBATCH --mem=32G
#SBATCH --gres=gpu:1

# Shard @@TAG@@: @@NJOBS@@ inference-only AF3 jobs, one GPU, sequential within the shard.
# Generated by scripts/generate_inference_shards.py - do not hand-edit the job list;
# regenerate shards instead if the CSV changes.
set -uo pipefail
source "${SLURM_SUBMIT_DIR}/config.sh"

IN_DIR="${ROOT}/inputs_inference"
OUT_DIR="${ROOT}/outputs_inference"
JOB_LIST="${ROOT}/job_lists/shard_@@TAG@@.txt"
mkdir -p "${OUT_DIR}" "${ROOT}/logs"

MAX_RETRIES=4
n_total=$(wc -l < "${JOB_LIST}")
n_done=0
while IFS= read -r NAME; do
    [[ -z "${NAME}" ]] && continue
    if [[ -f "${OUT_DIR}/${NAME}_model.cif" ]]; then
        echo "skip ${NAME}: already done"
        n_done=$((n_done + 1))
        continue
    fi
    ok=0
    for attempt in $(seq 1 "${MAX_RETRIES}"); do
        echo "--- [$((n_done + 1))/${n_total}] ${NAME} (attempt ${attempt}/${MAX_RETRIES}) ---"
        if SINGULARITY_BIND="${WEIGHTS_DIR}:/data/weights,${IN_DIR}:/data/af_input,${OUT_DIR}:/data/af_output" \
            singularity run --nv "${SIF}" \
            python3 /app/alphafold/run_alphafold.py \
            --json_path "/data/af_input/${NAME}.json" \
            --output_dir /data/af_output \
            --model_dir /data/weights \
            --norun_data_pipeline; then
            ok=1
            break
        fi
        echo "!!! ${NAME} failed on attempt ${attempt}; retrying after 20s"
        sleep 20
    done
    [[ "${ok}" -eq 1 ]] && n_done=$((n_done + 1)) || echo "XXX ${NAME} FAILED after ${MAX_RETRIES} attempts; continuing"
done < "${JOB_LIST}"

echo "=== Shard @@TAG@@ done: ${n_done}/${n_total} ==="
"""


def main() -> None:
    names = [n for n in JOB_LIST.read_text().splitlines() if n]
    n_shards = math.ceil(len(names) / SHARD_SIZE)
    width = max(3, len(str(n_shards)))

    JOB_LISTS_DIR.mkdir(exist_ok=True)
    SLURM_DIR.mkdir(exist_ok=True)
    LOGS_DIR.mkdir(exist_ok=True)

    for i in range(n_shards):
        chunk = names[i * SHARD_SIZE : (i + 1) * SHARD_SIZE]
        tag = str(i + 1).zfill(width)
        (JOB_LISTS_DIR / f"shard_{tag}.txt").write_text("\n".join(chunk) + "\n")
        sbatch_text = (
            SBATCH_TEMPLATE.replace("@@TAG@@", tag)
            .replace("@@NJOBS@@", str(len(chunk)))
            .replace("@@TIME@@", TIME_LIMIT)
        )
        (SLURM_DIR / f"infer_shard_{tag}.sbatch").write_text(sbatch_text)

    print(f"{n_shards} shards written ({SHARD_SIZE} jobs each, last shard has {len(names) - (n_shards - 1) * SHARD_SIZE}):")
    print(f"  job lists    -> {JOB_LISTS_DIR}/shard_*.txt")
    print(f"  sbatch files -> {SLURM_DIR}/infer_shard_*.sbatch")


if __name__ == "__main__":
    main()
