#!/usr/bin/env python3
"""Regenerate shards for inference jobs that have no output yet.

The original 10h shards were too short for the slow EBF2/EBF3_NFKB2 pairs, so
reruns get 36h (the max the `gpu1` QoS allows) and fewer jobs per shard.

Output:
  job_lists/rerun_XXX.txt
  slurm_shards/infer_rerun_XXX.sbatch
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JOB_LIST = ROOT / "job_list_inference.txt"
OUT_DIR = ROOT / "outputs_inference"
JOB_LISTS_DIR = ROOT / "job_lists"
SLURM_DIR = ROOT / "slurm_shards"
LOGS_DIR = ROOT / "logs"

SHARD_SIZE = 10
TIME_LIMIT = "36:00:00"

SBATCH_TEMPLATE = r"""#!/bin/bash
#SBATCH --job-name=af3_rerun_@@TAG@@
#SBATCH --output=logs/af3_rerun_@@TAG@@_%j.log
#SBATCH --time=@@TIME@@
#SBATCH --cpus-per-task=4
#SBATCH --mem=32G
#SBATCH --gres=gpu:1

# Rerun shard @@TAG@@: @@NJOBS@@ inference-only AF3 jobs that produced no output
# in the first pass. Generated by scripts/generate_rerun_shards.py.
set -uo pipefail
source "${SLURM_SUBMIT_DIR}/config.sh"

IN_DIR="${ROOT}/inputs_inference"
OUT_DIR="${ROOT}/outputs_inference"
JOB_LIST="${ROOT}/job_lists/rerun_@@TAG@@.txt"
mkdir -p "${OUT_DIR}" "${ROOT}/logs"

MAX_RETRIES=4
n_total=$(wc -l < "${JOB_LIST}")
n_done=0
while IFS= read -r NAME; do
    [[ -z "${NAME}" ]] && continue
    if [[ -f "${OUT_DIR}/${NAME}_model.cif" ]]; then
        echo "skip ${NAME}: already done"
        n_done=$((n_done + 1))
        continue
    fi
    ok=0
    for attempt in $(seq 1 "${MAX_RETRIES}"); do
        echo "--- [$((n_done + 1))/${n_total}] ${NAME} (attempt ${attempt}/${MAX_RETRIES}) ---"
        # Attempts 3+ disable XLA autotuning, which is what killed a handful of
        # jobs with "Autotuning failed for HLO: ... No valid config found!".
        XLA_EXTRA=""
        [[ "${attempt}" -ge 3 ]] && XLA_EXTRA="--xla_gpu_autotune_level=0"
        if SINGULARITY_BIND="${WEIGHTS_DIR}:/data/weights,${IN_DIR}:/data/af_input,${OUT_DIR}:/data/af_output" \
            SINGULARITYENV_XLA_FLAGS="${XLA_EXTRA}" \
            singularity run --nv "${SIF}" \
            python3 /app/alphafold/run_alphafold.py \
            --json_path "/data/af_input/${NAME}.json" \
            --output_dir /data/af_output \
            --model_dir /data/weights \
            --norun_data_pipeline; then
            ok=1
            break
        fi
        echo "!!! ${NAME} failed on attempt ${attempt}; retrying after 20s"
        sleep 20
    done
    [[ "${ok}" -eq 1 ]] && n_done=$((n_done + 1)) || echo "XXX ${NAME} FAILED after ${MAX_RETRIES} attempts; continuing"
done < "${JOB_LIST}"

echo "=== Rerun shard @@TAG@@ done: ${n_done}/${n_total} ==="
"""


def main() -> None:
    names = [n for n in JOB_LIST.read_text().splitlines() if n]
    missing = [n for n in names if not (OUT_DIR / f"{n}_model.cif").exists()]
    if not missing:
        print("nothing to rerun - all inference outputs present")
        return

    n_shards = math.ceil(len(missing) / SHARD_SIZE)
    width = max(3, len(str(n_shards)))

    JOB_LISTS_DIR.mkdir(exist_ok=True)
    SLURM_DIR.mkdir(exist_ok=True)
    LOGS_DIR.mkdir(exist_ok=True)

    for old in list(JOB_LISTS_DIR.glob("rerun_*.txt")) + list(SLURM_DIR.glob("infer_rerun_*.sbatch")):
        old.unlink()

    for i in range(n_shards):
        chunk = missing[i * SHARD_SIZE : (i + 1) * SHARD_SIZE]
        tag = str(i + 1).zfill(width)
        (JOB_LISTS_DIR / f"rerun_{tag}.txt").write_text("\n".join(chunk) + "\n")
        sbatch_text = (
            SBATCH_TEMPLATE.replace("@@TAG@@", tag)
            .replace("@@NJOBS@@", str(len(chunk)))
            .replace("@@TIME@@", TIME_LIMIT)
        )
        (SLURM_DIR / f"infer_rerun_{tag}.sbatch").write_text(sbatch_text)

    print(f"{len(missing)} missing jobs -> {n_shards} rerun shards ({TIME_LIMIT} each)")
    for i in range(n_shards):
        tag = str(i + 1).zfill(width)
        print(f"  slurm_shards/infer_rerun_{tag}.sbatch")


if __name__ == "__main__":
    main()
